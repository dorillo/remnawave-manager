export let lang = "ru";
try {
  lang = localStorage.getItem("fokus:lang") === "en" ? "en" : "ru";
} catch {}
export const t = (key) => words[lang][key] || key;
export function setLanguage(value) {
  lang = value;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem("fokus:lang", lang);
  } catch {}
}
export const date = (value) => {
  const d = new Date(value);
  return Number.isFinite(d.getTime())
    ? new Intl.DateTimeFormat(lang === "ru" ? "ru-RU" : "en-GB", {
        day: "numeric",
        month: "short",
        hour: "2-digit",
        minute: "2-digit",
      }).format(d)
    : "";
};
