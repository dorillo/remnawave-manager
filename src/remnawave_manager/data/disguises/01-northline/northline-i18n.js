export function getInterfaceLanguage() {
  return language;
}

export function getInterfaceLocale() {
  return language === 'ru' ? 'ru-RU' : 'en-US';
}

export function translate(value) {
  if (language === 'ru' || typeof value !== 'string' || !value) return value;
  const exact = EN.get(value);
  if (exact) return exact;
  if (value.endsWith(' — Line')) return `${translate(value.slice(0, -7))} — Line`;
  for (const [pattern, replacement] of PATTERNS)
    if (pattern.test(value)) return value.replace(pattern, replacement);
  return value;
}

export function setInterfaceLanguage(next) {
  if (!SUPPORTED.has(next) || next === language) return;
  language = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch {}
  location.reload();
}

export function initializeInterfaceLanguage() {
  document.documentElement.lang = language;

}

